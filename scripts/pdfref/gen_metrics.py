"""Generate lib/sheets/metrics.ts: Helvetica (= Arial) advance widths per 1000 em for ASCII 32-126."""
from pathlib import Path
import fitz

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "lib" / "sheets" / "metrics.ts"


def table(font):
    return [round(font.text_length(chr(c), 1000), 1) for c in range(32, 127)]


def fmt(vals):
    return ",".join(f"{v:g}" for v in vals)


def main():
    reg, bold = table(fitz.Font("helv")), table(fitz.Font("hebo"))
    src = f"""// Generated by scripts/pdfref/gen_metrics.py — do not edit.
// Helvetica (metric-compatible with Arial/Arimo) advance widths, units per 1000 em, chars 32..126.
const FIRST = 32;
export const REGULAR: readonly number[] = [{fmt(reg)}];
export const BOLD: readonly number[] = [{fmt(bold)}];

/** Advance width of one character in 1000-em units. */
export function charWidth(ch: string, bold: boolean): number {{
  const t = bold ? BOLD : REGULAR;
  const code = ch.charCodeAt(0);
  if (code >= FIRST && code < FIRST + t.length) return t[code - FIRST];
  if (code < 128) return t['n'.charCodeAt(0) - FIRST];
  return 556;
}}
"""
    OUT.write_text(src, encoding="utf-8")
    print(f"wrote {OUT} ({len(reg)} + {len(bold)} widths)")


if __name__ == "__main__":
    main()
